def normalize_text(value: str) -> str:
  value = unicodedata.normalize("NFKC", value or "")
  value = value.replace("‐", "-").replace("‑", "-").replace("–", "-").replace("—", "-")
  value = re.sub(r"\s*Quelle:\s*study\.learning\.wiley\.com\s*", " ", value, flags=re.I)
  return re.sub(r"\s+", " ", value).strip()


def normalized_key(value: str) -> str:
  value = normalize_text(value).casefold()
  value = re.sub(r"[^a-z0-9]+", " ", value)
  return re.sub(r"\s+", " ", value).strip()


def parse_record(record: dict) -> dict:
  options = {}
  correct = None
  selected = []
  for answer in record.get("answers") or []:
    match = re.match(r"^([A-Z])[.:)]\s*(.*)$", normalize_text(str(answer.get("text") or "")), re.I)
    if not match:
      continue
    letter = match.group(1).upper()
    options[letter] = normalize_text(match.group(2))
    if answer.get("correct") is True:
      if correct is not None:
        raise RuntimeError(f"Multiple correct answers in {record.get('question')}")
      correct = letter
    if answer.get("selected") is True:
      selected.append(letter)
  explicit = re.match(r"^([A-Z])[.:)]", normalize_text(str(record.get("correct") or "")), re.I)
  if explicit and correct and explicit.group(1).upper() != correct:
    raise RuntimeError(f"Conflicting explicit keys in {record.get('question')}")
  if explicit:
    correct = explicit.group(1).upper()
  response = record.get("responseSeconds")
  if not isinstance(response, (int, float)) or response < 0:
    raise RuntimeError(f"Missing responseSeconds in {record.get('question')}")
  if not correct or correct not in options or len(options) < 2:
    raise RuntimeError(f"Invalid answer structure in {record.get('question')}")
  return {
    "sourceId": str(record.get("id") or ""),
    "question": normalize_text(str(record.get("question") or "")),
    "options": options,
    "correct": correct,
    "selected": selected,
    "explanation": normalize_text(str(record.get("explanation") or "")),
    "responseSeconds": int(response),
  }


def corrected_record(record: dict) -> tuple[dict, dict | None]:
  key = normalized_key(record["question"])
  for prefix, correction in CONTENT_CORRECTIONS.items():
    if key.startswith(prefix):
      return {
        **record,
        "question": correction["question"],
        "explanation": correction["explanation"],
      }, {
        "beforeQuestion": record["question"],
        "afterQuestion": correction["question"],
        "answer": f"{record['correct']}: {record['options'][record['correct']]}",
        "reason": correction["reason"],
      }
  return record, None


def mapping_for(original_question: str) -> tuple[list[str], str]:
  key = normalized_key(original_question)
  for needle, requirements, topic in QUESTION_RULES:
    if needle in key:
      return requirements, topic
  raise RuntimeError(f"No Domain 2 mapping for: {original_question}")


def best_explanation_sentence(record: dict, letter: str) -> str:
  sentences = [part.strip() for part in re.split(r"(?<=[.!?])\s+", record["explanation"]) if part.strip()]
  if not sentences:
    return "The keyed concept is determined by the defining property in the stem."
  stop = {"that", "this", "with", "from", "have", "will", "into", "than", "only", "they", "their", "attack"}
  words = {
    word for word in re.findall(r"[a-z0-9]+", record["options"][letter].casefold())
    if len(word) >= 4 and word not in stop
  }
  return max(sentences, key=lambda sentence: sum(word in sentence.casefold() for word in words))


def option_reason(record: dict, letter: str) -> str:
  option = record["options"][letter]
  answer = record["options"][record["correct"]]
  detail = best_explanation_sentence(record, letter)
  if letter == record["correct"]:
    return f"{option} matches the defining condition in the stem. {detail}"
  return f"{option} does not satisfy the defining condition; the keyed result is {answer}. {detail}"


def content_for(record: dict, requirement_rows: list[dict], digest: str) -> dict:
  front = "\n".join(
    [record["question"]]
    + [f"{letter}: {text}" for letter, text in sorted(record["options"].items())]
  )
  wrong = [
    f"{letter} | {option_reason(record, letter)}"
    for letter in sorted(record["options"])
    if letter != record["correct"]
  ]
  back = f">> CORRECT: {record['correct']} |\n\n{record['explanation']}\n\nNicht:\n" + "\n".join(wrong)
  path = requirement_rows[0].get("sourcePath") or []
  tags = []
  for value in (path[2] if len(path) > 2 else "Domain 2.0", path[-1] if path else "Threats"):
    value = str(value)
    if value not in tags:
      tags.append(value)
  return {
    "noteId": f"newinfo-domain2-note-{digest}",
    "deckId": DECK_ID,
    "front": front,
    "back": back,
    "tags": tags,
    "extra": {"acronym": "", "examples": "", "port": "", "protocol": ""},
  }



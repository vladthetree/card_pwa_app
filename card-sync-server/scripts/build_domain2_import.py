def write_report(decisions: list[dict], excluded: list[dict]) -> None:
  corrected = [decision for decision in decisions if decision["verdict"] == "corrected"]
  lines = [
    "# Import-Prüfbericht",
    "",
    f"Deck: `{DECK_NAME}`",
    "",
    "- Quelldatensätze: 18",
    f"- Veröffentlicht: {len(decisions)}",
    f"- Unverändert fachlich freigegeben: {len(decisions) - len(corrected)}",
    f"- Mit gleicher markierter Antwort sprachlich/fachlich bereinigt: {len(corrected)}",
    f"- Mit übernommener Antwortzeit: {len(decisions)}",
    f"- Nicht erneut angelegt: {len(excluded)}",
    "",
    "## Nicht erneut angelegt",
    "",
  ]
  for item in excluded:
    lines.append(f"- **{item['question']}** — {item['reason']}")
  lines.extend(["", "## Bereinigte Formulierungen", ""])
  for decision in corrected:
    correction = decision["importTrace"]["correction"]
    lines.extend([
      f"- **Karte `{decision['cardId']}` / {correction['answer']}**",
      f"  - Vorher: {correction['beforeQuestion']}",
      f"  - Nachher: {correction['afterQuestion']}",
      f"  - Grund: {correction['reason']}",
    ])
  lines.extend(["", "## Importierte Karten", ""])
  for number, decision in enumerate(decisions, start=1):
    front_lines = decision["content"]["front"].splitlines()
    options = dict(re.findall(r"^([A-Z]):\s*(.+)$", decision["content"]["front"], re.M))
    correct = re.search(r">> CORRECT: ([A-Z])", decision["content"]["back"]).group(1)
    timing = decision["importTrace"]["responseSeconds"]
    lines.append(f"{number}. {front_lines[0]} — **{correct}: {options[correct]}** — Antwortzeit: {timing} s")
  REPORT_FILE.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def main() -> int:
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--source", type=Path, default=SOURCE_FILE)
  parser.add_argument("--requirements", type=Path, default=REQUIREMENTS_FILE)
  parser.add_argument("--db", type=Path, default=REPO_ROOT / "card-sync-server" / "sync.db")
  parser.add_argument("--decisions", type=Path, default=DECISIONS_FILE)
  args = parser.parse_args()

  raw = json.loads(args.source.read_text(encoding="utf-8-sig"))
  if not isinstance(raw, list) or len(raw) != 18:
    raise RuntimeError(f"Expected 18 source records, found {len(raw) if isinstance(raw, list) else 'non-list'}")
  records = [parse_record(item) for item in raw]
  keys = [normalized_key(record["question"]) for record in records]
  if len(set(keys)) != len(keys):
    raise RuntimeError("Duplicate stems inside Chapter 2 source")

  requirement_raw = json.loads(args.requirements.read_text(encoding="utf-8"))
  requirement_by_id = {item["requirementId"]: item for item in requirement_raw["requirements"]}
  conn = sqlite3.connect(args.db)
  conn.row_factory = sqlite3.Row
  user_rows = conn.execute(
    "SELECT user_id FROM users WHERE LOWER(TRIM(COALESCE(profile_name, '')))=LOWER('Vlad')"
  ).fetchall()
  if len(user_rows) != 1:
    conn.close()
    raise RuntimeError(f"Expected exactly one Vlad profile, found {len(user_rows)}")
  user_id = str(user_rows[0]["user_id"])
  active_rows = conn.execute(
    """SELECT r.id, x.front
       FROM shared_card_catalog x
       JOIN server_cards r ON r.id=x.id AND r.user_id=?
       WHERE x.canonical_user_id=? AND x.deleted_at IS NULL
         AND r.deleted_at IS NULL AND IFNULL(r.is_deleted, 0)=0""",
    (user_id, user_id),
  ).fetchall()
  conn.close()
  active_card_ids = {str(row["id"]) for row in active_rows}
  active_stems = {
    normalized_key(str(row["front"] or "").splitlines()[0]): str(row["id"])
    for row in active_rows
  }

  decisions = []
  excluded = []
  for original in records:
    existing_card = active_stems.get(normalized_key(original["question"]))
    if existing_card and not existing_card.startswith("newinfo-domain2-"):
      excluded.append({
        "question": original["question"],
        "reason": f"Bereits als aktive Karte `{existing_card}` in Chapter 1 vorhanden; Antwort {original['correct']} bleibt dort erhalten.",
      })
      continue
    record, correction = corrected_record(original)
    requirements, topic = mapping_for(original["question"])
    unknown = [requirement for requirement in requirements if requirement not in requirement_by_id]
    if unknown:
      raise RuntimeError("Unknown requirement(s): " + ", ".join(unknown))
    decisions.append(build_decision(
      original,
      record,
      correction,
      requirements,
      [requirement_by_id[requirement] for requirement in requirements],
      topic,
      user_id,
      active_card_ids,
    ))
  if len(decisions) != 17 or len(excluded) != 1:
    raise RuntimeError(f"Expected 17 decisions and 1 active duplicate, found {len(decisions)} and {len(excluded)}")
  if len({decision["cardId"] for decision in decisions}) != len(decisions):
    raise RuntimeError("Deterministic card ID collision")

  args.decisions.parent.mkdir(parents=True, exist_ok=True)
  args.decisions.write_text(json.dumps({
    "schemaVersion": "reviewed-domain2-import-1",
    "replaceRegistry": False,
    "deck": {"id": DECK_ID, "name": DECK_NAME, "parentDeckId": None},
    "sourceDirectory": str(SOURCE_DIR.relative_to(REPO_ROOT)),
    "answerPolicy": "answers[].correct and correct are authoritative; selected is not a solution key",
    "metricsPolicy": {
      "sourceField": "responseSeconds",
      "targetField": "createState.metadata.answerTiming",
      "missingValues": "omitted, never invented",
    },
    "decisions": decisions,
  }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
  write_report(decisions, excluded)
  print(json.dumps({
    "sourceRecords": len(records),
    "publishedCandidates": len(decisions),
    "approved": sum(decision["verdict"] == "approved" for decision in decisions),
    "correctedSameAnswer": sum(decision["verdict"] == "corrected" for decision in decisions),
    "existingDuplicate": len(excluded),
    "withResponseSeconds": len(decisions),
    "decisionFile": str(args.decisions),
    "report": str(REPORT_FILE),
  }, ensure_ascii=False, indent=2))
  return 0



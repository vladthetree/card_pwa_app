export const SECURITY_VISUAL_CARD_IDS = Object.keys(SECURITY_VISUALS)

export function getSecurityVisualForCard(card: { id: string; front: string; back: string }): SecurityVisual | null {
  const visual = SECURITY_VISUALS[card.id]
  if (!visual || fnv1a32(card.front) !== visual.questionFingerprint) return null
  const answer = parseMcAnswer(card.back)
  return answer.correctOptions.length === 1 && answer.correct === visual.expectedCorrect ? visual : null
}
